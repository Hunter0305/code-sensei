"""
Adaptive Models — Personalized Learning Roadmaps
"""
from django.db import models
from django.contrib.auth import get_user_model
from learning.models import Concept

User = get_user_model()


class LearningRoadmap(models.Model):
    """
    A personalized learning path generated by the AI for a specific user.
    """
    user       = models.ForeignKey(User, on_delete=models.CASCADE, related_name='roadmaps')
    title      = models.CharField(max_length=200, default='Personalized Learning Path')
    goal       = models.TextField(blank=True, default='')
    
    is_active  = models.BooleanField(default=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = 'adaptive_roadmap'
        ordering = ['-created_at']

    def __str__(self):
        return f'{self.user.email} -> {self.title}'

    def disable_others(self):
        """Ensure only one roadmap is active per user."""
        LearningRoadmap.objects.filter(user=self.user, is_active=True).exclude(id=self.id).update(is_active=False)


class RoadmapNode(models.Model):
    """
    A single step in a Learning Roadmap.
    Links to a specific concept and includes AI-generated advice.
    """
    STATUS_CHOICES = [
        ('pending',     'Pending'),
        ('in_progress', 'In Progress'),
        ('completed',   'Completed'),
    ]

    roadmap = models.ForeignKey(LearningRoadmap, on_delete=models.CASCADE, related_name='nodes')
    concept = models.ForeignKey(Concept, on_delete=models.CASCADE, related_name='roadmap_nodes')
    
    order           = models.IntegerField(default=0)
    ai_rationale    = models.TextField(help_text="Why the AI suggested this step.")
    estimated_hours = models.FloatField(default=1.0)
    
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='pending')

    class Meta:
        db_table = 'adaptive_roadmap_node'
        ordering = ['roadmap', 'order']

    def __str__(self):
        return f'Step {self.order}: {self.concept.name}'
